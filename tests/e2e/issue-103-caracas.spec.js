import { test, expect } from '@playwright/test'
test('la ficha de hotel-majestic documenta 1936 y conserva la etapa posterior', async ({page}) => {
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.route('**/datos/crece.json', r => r.fulfill({status:404}))
 await page.route(/\/(datos\/(ciudad\.pak|arboles\.bin|relieve\.bin)|plano\/[^?]*\.(webp|png))(\?.*)?$/,r=>r.fulfill({status:404}))
 await page.goto('/?sinintro&capture')
 await page.waitForFunction(()=>window.lab?.ready)
 await page.evaluate(()=>{const l=window.lab;l.ciudad.U.uEpocaDe.value=l.ciudad.U.uEpocaA.value=5;l.ciudad.U.uOlaEpoca.value=9000;l.cam.jump({...l.coords.aMundo(8260,7520),dist:450,yaw:0,pitch:1});l.pedirCuadro(3)})
 await page.locator('#marcas .marca.ver .tag',{hasText:'Hotel Majestic'}).click()
 await expect(page.locator('#ficha h2')).toHaveText('Hotel Majestic')
 await expect(page.locator('#ficha .texto p.epoca.rige')).toContainText('1930')
 await page.evaluate(()=>{const l=window.lab;l.ciudad.U.uEpocaDe.value=l.ciudad.U.uEpocaA.value=6;l.pedirCuadro(3)})
 await expect(page.locator('#ficha .era')).toHaveText('Hacia 1946')
 await expect(page.locator('#ficha .texto p.epoca.rige')).toContainText('1949')
})
